import AppKit
import ClipStackCore

/// Watches the system clipboard and records new text copies.
///
/// macOS has no "clipboard changed" notification, so this checks `changeCount` (a cheap integer)
/// twice a second and only reads the clipboard when it actually changed.
final class ClipboardMonitor {
    private let pasteboard = NSPasteboard.general
    private let history: ClipHistory
    private let isPaused: () -> Bool
    private var lastChangeCount = -1
    private var timer: Timer?

    /// Markers that password managers and other apps put on the clipboard to say
    /// "don't record this" (see nspasteboard.org).
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "public.file-url", // copied files: out of scope for now, and their "text" is only a file name
    ]

    init(history: ClipHistory, isPaused: @escaping () -> Bool) {
        self.history = history
        self.isPaused = isPaused
    }

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common) // keep running while menus are open
        self.timer = timer
        check()
    }

    /// Marks the current clipboard as already seen (used after ClipStack writes to it itself).
    func skipCurrent() {
        lastChangeCount = pasteboard.changeCount
    }

    private func check() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        // While paused, the contents are never read — only the change counter.
        guard !isPaused() else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes),
              let text = pasteboard.string(forType: .string) else { return }
        history.add(text)
    }
}
